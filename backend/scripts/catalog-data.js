const rupees = (r) => r * 100;

/** Builds variants for every colour × storage combination. */
function variants(prefix, colors, configs, stockFn = () => 60) {
  const out = [];
  for (const [ci, [color, colorHex]] of colors.entries()) {
    for (const [si, { storage, ram, price, mrp }] of configs.entries()) {
      out.push({
        sku: `${prefix}-${ram.replace(/\D/g, '')}-${storage.replace(/\D/g, '')}${storage.includes('TB') ? 'T' : ''}-${color.split(/\s+/).map((w) => w.replace(/[^A-Za-z]/g, '').slice(0, 3)).join('').toUpperCase()}`,
        color,
        colorHex,
        storage,
        ram,
        priceCents: rupees(price),
        mrpCents: rupees(mrp ?? price),
        stock: stockFn(ci, si),
      });
    }
  }
  return out;
}

